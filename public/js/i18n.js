function translateTree(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const value = translateValue(node.nodeValue);
    if (value !== node.nodeValue) node.nodeValue = value;
  }
  if (root.nodeType === Node.ELEMENT_NODE) {
    for (const attr of ["aria-label", "title", "placeholder"]) {
      if (root.hasAttribute(attr))
        root.setAttribute(attr, translateValue(root.getAttribute(attr)));
    }
    root
      .querySelectorAll("[aria-label], [title], [placeholder]")
      .forEach((element) => {
        for (const attr of ["aria-label", "title", "placeholder"]) {
          if (element.hasAttribute(attr))
            element.setAttribute(
              attr,
              translateValue(element.getAttribute(attr)),
            );
        }
      });
  }
}

export function initLanguage() {
  document.documentElement.lang = appLocale;
  if (!isEnglish) return;
  document.title = t(document.title);
  translateTree(document.body);
  new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData") {
        const value = translateValue(record.target.nodeValue);
        if (value !== record.target.nodeValue) record.target.nodeValue = value;
      } else if (record.type === "attributes") {
        const attribute = record.attributeName;
        const value = translateValue(record.target.getAttribute(attribute));
        if (value !== record.target.getAttribute(attribute))
          record.target.setAttribute(attribute, value);
      } else {
        record.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE) {
            const value = translateValue(node.nodeValue);
            if (value !== node.nodeValue) node.nodeValue = value;
          } else if (node.nodeType === Node.ELEMENT_NODE) translateTree(node);
        });
      }
    }
  }).observe(document.body, {
    attributes: true,
    attributeFilter: ["aria-label", "title", "placeholder"],
    childList: true,
    characterData: true,
    subtree: true,
  });
}
